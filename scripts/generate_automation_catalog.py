"""Generate docs/automations_and_scripts.md from every package and scripts.yaml.

The catalog lists each automation and script with its ``description:`` field,
grouped by the source file that owns it. Private packages are read from their
``private_templates/*.tmpl`` source and rendered in memory with the committed
synthetic values, so the output is identical locally and in CI and never
contains real private values.

Usage:
    uv run python scripts/generate_automation_catalog.py          # write
    uv run python scripts/generate_automation_catalog.py --check  # verify
"""

from __future__ import annotations

import argparse
from dataclasses import dataclass
import json
from pathlib import Path
import sys

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from scripts.render_private_config import MARKER  # noqa: E402

CATALOG = ROOT / "docs" / "automations_and_scripts.md"
MANIFEST = ROOT / "docs" / "private_config_manifest.json"
EXAMPLE_VALUES = ROOT / "examples" / "private_values.example.json"


class _Loader(yaml.SafeLoader):
    """SafeLoader that tolerates Home Assistant tags such as !secret/!include."""


def _any_tag(loader: yaml.SafeLoader, _suffix: str, node: yaml.Node):
    if isinstance(node, yaml.ScalarNode):
        return loader.construct_scalar(node)
    if isinstance(node, yaml.SequenceNode):
        return loader.construct_sequence(node, deep=True)
    return loader.construct_mapping(node, deep=True)


_Loader.add_multi_constructor("!", _any_tag)


@dataclass(frozen=True)
class Item:
    kind: str  # "automation" or "script"
    key: str  # automation id or script object id
    alias: str
    description: str
    mode: str


def _source_files() -> list[tuple[str, str]]:
    """Return (display path, YAML text) for every config file that can hold items."""
    values = json.loads(EXAMPLE_VALUES.read_text(encoding="utf-8"))
    manifest = json.loads(MANIFEST.read_text(encoding="utf-8"))["files"]
    rendered = {entry["output"]: entry["template"] for entry in manifest}

    def render(template: str) -> str:
        return MARKER.sub(
            lambda m: json.dumps(values[m.group(1)]) if m.group(2) == "json" else values[m.group(1)],
            template,
        )

    files: list[tuple[str, str]] = [("scripts.yaml", (ROOT / "scripts.yaml").read_text(encoding="utf-8"))]
    package_names = {p.name for p in (ROOT / "packages").glob("*.yaml")}
    package_names |= {Path(out).name for out in rendered if out.startswith("packages/")}
    for name in sorted(package_names):
        output = f"packages/{name}"
        if output in rendered:
            template = rendered[output]
            files.append((template, render((ROOT / template).read_text(encoding="utf-8"))))
        else:
            files.append((output, (ROOT / output).read_text(encoding="utf-8")))
    return files


def _text(value) -> str:
    return " ".join(str(value).split()) if value not in (None, "") else ""


def collect() -> dict[str, list[Item]]:
    """Map each source file to the automations and scripts it defines."""
    result: dict[str, list[Item]] = {}
    for path, text in _source_files():
        data = yaml.load(text, Loader=_Loader)
        autos: list = []
        scripts: dict = {}
        if path == "scripts.yaml":
            scripts = data or {}
        elif isinstance(data, dict):
            for key, value in data.items():
                domain = str(key).split(" ")[0]
                if domain == "automation":
                    autos += value if isinstance(value, list) else [value]
                elif domain == "script" and isinstance(value, dict):
                    scripts.update(value)
        items: list[Item] = []
        for auto in autos:
            if isinstance(auto, dict):
                items.append(Item("automation", _text(auto.get("id")), _text(auto.get("alias")),
                                  _text(auto.get("description")), _text(auto.get("mode")) or "single"))
        for key, script in scripts.items():
            if isinstance(script, dict):
                items.append(Item("script", str(key), _text(script.get("alias")),
                                  _text(script.get("description")), _text(script.get("mode")) or "single"))
        if items:
            result[path] = items
    return result


def _cell(value: str) -> str:
    return value.replace("|", "\\|") or "—"


def render_catalog(catalog: dict[str, list[Item]]) -> str:
    autos = sum(1 for items in catalog.values() for i in items if i.kind == "automation")
    scripts = sum(1 for items in catalog.values() for i in items if i.kind == "script")
    lines = [
        "# Automations and Scripts Catalog",
        "",
        "<!-- Generated by scripts/generate_automation_catalog.py. Do not edit by hand. -->",
        "",
        "Every Home Assistant automation and script defined in this repo, with the",
        "`description:` field from its YAML. Private packages are listed under their",
        "`private_templates/*.tmpl` source and rendered with the synthetic example",
        "values, so placeholder names such as `example_zone_05` stand in for private ones.",
        "",
        f"Totals: **{autos} automations** and **{scripts} scripts** across {len(catalog)} files.",
        "",
        "To keep this current, add a `description:` to every new automation or script",
        "and regenerate:",
        "",
        "```bash",
        "uv run python scripts/generate_automation_catalog.py",
        "```",
        "",
        "`tests/test_automation_script_descriptions.py` fails when a description is",
        "missing or this file is stale. Topic docs in `docs/` and the Allium specs in",
        "`specs/` hold the deeper behavior notes for each area.",
        "",
        "## Contents",
        "",
    ]
    for path in catalog:
        anchor = path.replace("/", "").replace(".", "").lower()
        lines.append(f"- [`{path}`](#{anchor})")
    for path, items in catalog.items():
        lines += ["", f"## `{path}`", ""]
        autos_in = [i for i in items if i.kind == "automation"]
        scripts_in = [i for i in items if i.kind == "script"]
        if autos_in:
            lines += ["### Automations", "", "| ID | Alias | Mode | Description |", "| --- | --- | --- | --- |"]
            lines += [f"| `{_cell(i.key)}` | {_cell(i.alias)} | {i.mode} | {_cell(i.description)} |" for i in autos_in]
            lines.append("")
        if scripts_in:
            lines += ["### Scripts", "", "| Script | Alias | Mode | Description |", "| --- | --- | --- | --- |"]
            lines += [f"| `script.{i.key}` | {_cell(i.alias)} | {i.mode} | {_cell(i.description)} |" for i in scripts_in]
            lines.append("")
    while lines and lines[-1] == "":
        lines.pop()
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if the catalog is stale")
    args = parser.parse_args()
    content = render_catalog(collect())
    if args.check:
        if not CATALOG.is_file() or CATALOG.read_text(encoding="utf-8") != content:
            print(f"{CATALOG.relative_to(ROOT)} is stale; regenerate it.", file=sys.stderr)
            return 1
        return 0
    CATALOG.write_text(content, encoding="utf-8")
    print(f"Wrote {CATALOG.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
